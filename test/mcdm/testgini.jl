    decisionMat = [
        1325 1825 1800 1000 1550 1800; 1375 1525 1800 1000 1500 1650;
        1275 1550 1800 1000 1650 1525; 1200 1750 1800 800 1450 1750;
        1025 1950 1500 1000 1650 1600; 900 1825 1800 1000 1650 1525;
        1300 1650 1650 850 1550 1700; 975 1825 1725 1000 1550 1600;
        1200 1400 1725 800 1800 1750; 1250 1550 1800 950 1450 1650;
        1275 1700 1725 1000 1425 1500; 1275 1525 1725 750 1600 1725;
        1150 1675 1650 950 1475 1675; 1000 1850 1575 850 1600 1650;
        600 1775 1800 1000 1600 1725; 1250 1575 1575 850 1550 1700;
        950 1925 1500 900 1650 1550; 1150 1675 1575 800 1550 1725;
        1300 1650 1725 750 1275 1750; 1175 1525 1650 850 1650 1575;
        775 1875 1800 1000 1300 1575; 1125 1500 1650 700 1625 1725;
        1200 1550 1425 850 1500 1775; 900 1600 1800 1000 1500 1475;
        1225 1350 1575 850 1650 1625; 1025 1700 1725 850 1375 1550;
        1175 1825 1425 850 1375 1550; 1125 1650 1650 850 1250 1650;
